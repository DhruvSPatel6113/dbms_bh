const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const MAX_ATTEMPTS = Number(process.env.GATE_MAX_ATTEMPTS || 3);
const MIN_TESTS = Number(process.env.GATE_MIN_TESTS || 150);
const MAX_FLAKY = Number(process.env.GATE_MAX_FLAKY || 0);
const OUT = path.join(__dirname, '..', 'gate-result.json');

function runJest(onlyFailures) {
  const args = ['jest', '--runInBand', '--json', `--outputFile=${OUT}`];
  if (onlyFailures) args.push('--onlyFailures');
  
  console.log(`[gate] Executing: npx ${args.join(' ')}`);
  const res = spawnSync('npx', args, { 
    stdio: 'inherit', 
    shell: process.platform === 'win32',
    cwd: path.join(__dirname, '..')
  });

  if (!fs.existsSync(OUT)) {
    console.error('[gate] Error: Output file gate-result.json was not generated by Jest.');
    process.exit(1);
  }

  const json = JSON.parse(fs.readFileSync(OUT, 'utf8'));
  return { status: res.status, json };
}

function failedNames(json) {
  if (!json.testResults) return [];
  return json.testResults.flatMap(f =>
    f.assertionResults.filter(t => t.status === 'failed').map(t => `${f.name} :: ${t.fullName}`)
  );
}

console.log('================ STARTING STRICT TDD QUALITY GATE ================');
let { json } = runJest(false);
const total = json.numTotalTests || 0;
const firstFailures = new Set(failedNames(json));
let remaining = new Set(firstFailures);
let attempt = 1;

while (remaining.size > 0 && attempt < MAX_ATTEMPTS) {
  attempt++;
  console.log(`\n[gate] Attempt ${attempt}/${MAX_ATTEMPTS}: re-running ${remaining.size} failed test(s)\n`);
  ({ json } = runJest(true));
  remaining = new Set(failedNames(json));
}

const flaky = [...firstFailures].filter(n => !remaining.has(n));

console.log('\n==================== TDD GATE FINAL REPORT ====================');
console.log(`Total assertions evaluated: ${total}`);
console.log(`Failed on initial run:      ${firstFailures.size}`);
console.log(`Flaky tests recovered:      ${flaky.length}`);
console.log(`Remaining failing tests:    ${remaining.size}`);
console.log(`Pending / Skipped tests:    ${json.numPendingTests || 0}`);

if (flaky.length) {
  console.log('\nFLAKY DETECTIONS:\n - ' + flaky.join('\n - '));
}
if (remaining.size) {
  console.log('\nACTIVE FAILURES:\n - ' + [...remaining].join('\n - '));
}

let ok = true;
if (remaining.size > 0) {
  console.error('\n[GATE FAILED] Active test failures detected.');
  ok = false;
}
if (total < MIN_TESTS) {
  console.error(`\n[GATE FAILED] Insufficient test count: evaluated ${total}, required >= ${MIN_TESTS}.`);
  ok = false;
}
if (flaky.length > MAX_FLAKY) {
  console.error(`\n[GATE FAILED] Flaky tests detected: found ${flaky.length}, maximum allowed is ${MAX_FLAKY}.`);
  ok = false;
}
if (json.numPendingTests > 0) {
  console.error('\n[GATE FAILED] Skipped or todo tests are strictly prohibited in CI.');
  ok = false;
}

if (ok) {
  console.log('\n>>> GATE PASSED: 100% of tests green, zero flakiness, and test count requirements met. <<<');
  process.exit(0);
} else {
  console.error('\n>>> BUILD BLOCKED: Gate requirements not satisfied. <<<');
  process.exit(1);
}

